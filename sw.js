self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(CORE_ASSETS)).catch(() => {})
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k.startsWith('aetheros-shell-') && k !== CACHE_NAME).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  // Live API and proxied images must never become cached shell HTML fallbacks.
  if (new URL(req.url).pathname.startsWith('/api/')) return;
  const url = new URL(req.url);

  // Only cache same-origin static assets & shell scripts/styles
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    fetch(req)
      .then((res) => {
        if (res && res.status === 200) {
          const copy = res.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(req, copy)).catch(() => {});
        }
        return res;
      })
      .catch(() => caches.match(req).then(async cached => {
        if(cached)return cached;
        if(req.mode==='navigate')return (await caches.match('./index.html')) || new Response('Offline',{status:503});
        return new Response('Asset unavailable offline',{status:503,headers:{'Content-Type':'text/plain'}});
      }))
  );
});
