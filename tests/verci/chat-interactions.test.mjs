import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { Messages } from '../../src/vendor/verci/viz/native.js';
import { parseLRC } from '../../src/vendor/verci/lrc.js';
const dom=new JSDOM('<main id="stage"></main>',{pretendToBeVisual:true});
globalThis.document=dom.window.document;globalThis.requestAnimationFrame=fn=>{fn();return 1;};
const root=document.getElementById('stage');
const L=parseLRC('[00:00]I love you\n[00:04]Hello world\n[00:08]Another line');
const ctx={lyrics:L,song:{title:'Song',artist:'Singer',artwork:''},opts:{gifs:()=>false,stickers:()=>false}};
let viz=new Messages(root,ctx).mount();
const bubble=viz.bubble(1,L.lines[1]);viz.inner.append(bubble);
assert.equal(bubble.querySelector('.chat-message-actions'),null);
bubble.dispatchEvent(new dom.window.MouseEvent('contextmenu',{bubbles:true,cancelable:true}));
assert.ok(viz.ph.querySelector('[role=dialog]'));
const find=(selector,text)=>[...viz.ph.querySelectorAll(selector)].find(e=>e.textContent===text);
find('.chat-picker-emoji','❤️').click();
assert.equal(bubble.querySelector('.chat-reaction-pill').textContent,'❤️');
assert.equal(bubble.querySelector('p').textContent,'Hello world','reaction not inserted into lyric text');
assert.equal(viz.ph.querySelector('[role=dialog]'),null);
bubble.querySelector('.chat-reaction-pill').click();find('.chat-picker-more','+').click();
assert.equal(viz.ph.querySelectorAll('.chat-picker-emoji').length,24);
find('.chat-menu-action','Remove reaction').click();assert.equal(bubble.querySelector('.chat-reaction-pill'),null);
bubble.dispatchEvent(new dom.window.MouseEvent('contextmenu',{bubbles:true,cancelable:true}));
find('.chat-menu-action','Reply').click();
assert.equal(viz.ph.querySelector('.chat-selected-lyric'),null,'reply thread does not repeat quoted lyrics');
const textarea=viz.ph.querySelector('textarea');
assert.equal(document.activeElement,textarea);
textarea.value='<img src=x onerror=alert(1)> hello';
viz.ph.querySelector('form').dispatchEvent(new dom.window.Event('submit',{bubbles:true,cancelable:true}));
assert.equal(viz.ph.querySelectorAll('.chat-local-reply').length,1);
assert.equal(viz.ph.querySelector('.chat-local-reply img'),null,'local reply is text only');
assert.match(viz.ph.querySelector('.chat-local-reply').textContent,/You · local reply/);
assert.equal(bubble.querySelector('.chat-reply-count').textContent,'↪ 1 reply');
viz.ph.querySelector('[role=dialog]').dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
assert.equal(viz.ph.querySelector('[role=dialog]'),null);
// Rebuilt TTML/seek bubbles and scene remounts retain the same session notes/reactions.
const rebuilt=viz.bubble(1,L.lines[1]);viz.inner.append(rebuilt);
assert.equal(rebuilt.querySelector('.chat-reply-count').textContent,'↪ 1 reply');
viz.destroy();viz=new Messages(root,ctx).mount();
const again=viz.bubble(1,L.lines[1]);viz.inner.append(again);
again.querySelector('.chat-reply-count').click();
assert.equal(viz.ph.querySelectorAll('.chat-local-reply').length,1);
assert.match(viz.ph.querySelector('.chat-local-note').textContent,/not sent to anyone/);
viz.destroy();assert.equal(root.children.length,0);
// A different lyrics object gets a fresh local session.
const L2=parseLRC('[00:00]Hello world');viz=new Messages(root,{...ctx,lyrics:L2}).mount();
const fresh=viz.bubble(0,L2.lines[0]);assert.equal(fresh.querySelector('.chat-reply-count'),null);
viz.destroy();
console.log('Message-attached picker, expanded emoji set, remove reaction, local replies, counts, threads, Escape and rebuild persistence verified.');

// No visible dropdown; keyboard context menu and touch-style hold remain available.
viz=new Messages(root,ctx).mount();
const keyboardBubble=viz.bubble(0,L.lines[0]);viz.inner.append(keyboardBubble);
keyboardBubble.dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:'F10',shiftKey:true,bubbles:true,cancelable:true}));
assert.ok(viz.ph.querySelector('[role=dialog]'),'Shift+F10 opens the context menu');
viz.chatInteractions.close();
const hold=new dom.window.Event('pointerdown',{bubbles:true});
Object.assign(hold,{button:0,clientX:10,clientY:10});keyboardBubble.dispatchEvent(hold);
await new Promise(resolve=>setTimeout(resolve,480));
assert.ok(viz.ph.querySelector('[role=dialog]'),'holding a lyric opens the context menu');
viz.destroy();
