import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {localChatTime,messageTime} from '../../src/vendor/verci/viz/chat-clock.js';
import {Messages} from '../../src/vendor/verci/viz/native.js';
import {parseLRC} from '../../src/vendor/verci/lrc.js';
assert.equal(localChatTime(new Date(2026,10,22,9,5)),'09:05');
assert.equal(localChatTime(new Date(2026,10,22,23,59)),'23:59');
const L=parseLRC('[00:03]I miss you\n[00:07]I miss you\n[00:11]I miss you');
assert.equal(messageTime(L,'test',new Date(2026,10,22,14,27)),'14:27');
assert.equal(messageTime(L,'test',new Date(2026,10,22,15,0)),'14:27','rebuild preserves send time');
assert.equal(messageTime({},'test',new Date(2026,10,22,15,0)),'15:00','per-song isolation');
const dom=new JSDOM('<main></main>');globalThis.document=dom.window.document;globalThis.requestAnimationFrame=()=>1;
const viz=new Messages(document.querySelector('main'),{song:{title:'Track',artist:'Singer'},lyrics:L,opts:{gifs:()=>false,stickers:()=>false}}).mount();
assert.equal(viz.ph.querySelector('.chat-clock').textContent,localChatTime());
const bubble=viz.bubble(0,L.lines[0]);
assert.equal(bubble.querySelector('time').textContent,localChatTime());
assert.notEqual(bubble.querySelector('time').textContent,'0:03','not lyric playback time');
assert.ok(viz.ph.querySelector('.kb-suggestions'));
assert.ok(viz.ph.querySelector('.composer-camera'));
viz.inner.append(bubble);
viz.chatInteractions.openThread(0,true);
const input=viz.ph.querySelector('textarea');input.value='hello';
viz.ph.querySelector('form').dispatchEvent(new dom.window.Event('submit',{bubbles:true,cancelable:true}));
assert.equal(viz.ph.querySelector('.chat-local-reply time').textContent,localChatTime());
assert.ok(viz.ph.querySelector('.chat-local-reply').classList.contains('message-arrival'));
viz.destroy();
