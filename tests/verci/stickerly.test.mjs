import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { FEATURED_STICKERS, stickerlyURL, cleanSticker, customStickers, pickStickerly, attachStickerly } from '../../src/vendor/verci/providers/stickerly.js';
const url=FEATURED_STICKERS[0].url;
assert.equal(FEATURED_STICKERS.length,9);
assert.equal(stickerlyURL(url),url);
for(const u of ['http://stickerly.pstatic.net/sticker_pack/x.png','https://evil.test/a.png','https://stickerly.pstatic.net.evil.test/sticker_pack/x.png','javascript:alert(1)','https://sticker.ly/share/TEST','https://stickerly.pstatic.net/sticker_pack/a.svg',url+'?track=1',url+'#x','https://user:pass@stickerly.pstatic.net/sticker_pack/x.png']) assert.equal(stickerlyURL(u),null,u);
assert.equal(cleanSticker({url,mood:'made-up'}),null);
assert.equal(customStickers(null).length,0);
assert.equal(customStickers(Array.from({length:70},()=>({url,mood:'love'}))).length,50);
assert.equal(pickStickerly('anger'),null,'heart stickers are not used for unrelated moods');
assert.deepEqual(pickStickerly('love',17),pickStickerly('love',17));
const custom={url,mood:'sad',name:'My saved sticker'};
assert.equal(pickStickerly('sad',0,[custom]).name,'My saved sticker');
assert.equal(pickStickerly('sad',0,[{...custom,url:url.replace('.png','.gif')}],true),null,'reduced motion disallows animated imports');
const dom=new JSDOM('<div id="sticker"><span>fallback</span><strong>LOCAL</strong></div>');
globalThis.document=dom.window.document;
const sticker=document.getElementById('sticker');
attachStickerly(sticker,{mood:'love'},{stickerSource:()=> 'local'},0,1,false);
assert.equal(sticker.querySelector('img'),null,'local-only setting performs no remote load');
attachStickerly(sticker,{mood:'love'},{stickerSource:()=> 'stickerly'},0,1,false);
const img=sticker.querySelector('img');assert.ok(img);assert.equal(img.referrerPolicy,'no-referrer');
assert.equal(img.hidden,true,'local fallback stays until remote image loads');
img.onload();assert.equal(img.hidden,false);assert.ok(sticker.classList.contains('has-stickerly-image'));
img.onerror();assert.equal(sticker.querySelector('img'),null);assert.equal(sticker.classList.contains('has-stickerly-image'),false,'broken remote image restores fallback');
console.log('Sticker.ly featured assets, strict URL validation, custom mood mapping, motion preference and local fallback verified.');
