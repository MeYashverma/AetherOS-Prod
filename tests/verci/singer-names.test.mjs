import assert from 'node:assert/strict';
import {resolveSingerNames} from '../../src/vendor/verci/singer-names.js';
import {planTurns} from '../../src/vendor/verci/viz/native.js';
import {listenerReplyFor} from '../../src/vendor/verci/viz/listener-replies.js';
const lines=Array.from({length:7},(_,i)=>({text:'I miss you',speaker:0,t:i*4,tokens:[]}));
const lyrics={speakers:['Voice 1','Voice 2'],speakerIds:['v1','v2'],lines};
assert.deepEqual(resolveSingerNames(lyrics,{artist:'Don Toliver',title:'Lose My Mind (feat. Doja Cat)'}),{names:['Don Toliver','Doja Cat'],inferred:[0,1]});
assert.deepEqual(resolveSingerNames({...lyrics,speakerIds:['v2','v1']},{artist:'Alice & Bob'}).names,['Bob','Alice']);
assert.deepEqual(resolveSingerNames(lyrics,{artist:'Band Name'}).names,['Voice 1','Voice 2'],'do not map ambiguous artist counts');
assert.deepEqual(resolveSingerNames({...lyrics,speakers:['Named singer','Voice 2']},{artist:'Alice & Bob'},{v2:'Verified singer'}).names,['Named singer','Verified singer']);
assert.deepEqual(resolveSingerNames({...lyrics,speakerIds:['v1 v2','v3']},{artist:'Alice & Bob'}).inferred,[],'do not infer joint agent identities');
const p=planTurns(lyrics,'Artist');lyrics.speakers=['Alice','Bob'];
assert.notEqual(planTurns(lyrics,'Artist'),p,'singer name edits invalidate cached turn labels');
const plan=planTurns(lyrics,'Artist');
assert.equal(listenerReplyFor(lyrics,plan,1),null);
assert.ok(listenerReplyFor(lyrics,plan,2));
assert.equal(listenerReplyFor(lyrics,plan,3),null,'sparse cadence');
assert.equal(listenerReplyFor(lyrics,plan,2),listenerReplyFor(lyrics,plan,2),'deterministic across seeks');
assert.equal(listenerReplyFor(lyrics,{T:lines.map((_,i)=>({who:i%2}))},2),null,'do not interrupt existing alternating dialogue');

// Render fictional messages as separate opposite-side tiles, never lyric tokens.
const {JSDOM}=await import('jsdom');
const {Messages}=await import('../../src/vendor/verci/viz/native.js');
const {frameState}=await import('../../src/vendor/verci/viz/core.js');
const dom=new JSDOM('<main></main>');globalThis.document=dom.window.document;
globalThis.requestAnimationFrame=()=>1;
const solo={format:'TTML',speakers:['Voice 1'],speakerIds:['v1'],lines:lines.map(l=>({...l,end:l.t+4})),flat:[]};
const root=document.querySelector('main');
const ctx={song:{title:'Song',artist:'Singer'},lyrics:solo,opts:{gifs:()=>false,stickers:()=>false,emojis:()=>false}};
let viz=new Messages(root,ctx).mount();
viz.onLine({...frameState(solo,9),jump:true});
assert.ok(root.querySelector('.chat-fictional-reply.out'),'listener answers on the right during a solo');
assert.match(root.querySelector('.chat-fictional-reply').textContent,/Fictional listener · not lyrics/);
assert.equal(solo.lines.length,7,'does not insert invented lyrics into timeline');
viz.onLine({...frameState(solo,9),jump:true});
assert.equal(root.querySelectorAll('.chat-fictional-reply').length,1,'seeking does not duplicate replies');
viz.destroy();
viz=new Messages(root,{...ctx,opts:{...ctx.opts,listenerReplies:()=>false}}).mount();
viz.onLine({...frameState(solo,9),jump:true});
assert.equal(root.querySelector('.chat-fictional-reply'),null,'listener mode can be disabled');viz.destroy();
