import assert from 'node:assert/strict';
import { lyricReaction, reactionGif, addChatReaction } from '../../src/vendor/verci/viz/chat-reactions.js';
import { JSDOM } from 'jsdom';
const reaction=lyricReaction('I love you with all my heart',3,'Duet');
assert.deepEqual(reaction,lyricReaction('I love you with all my heart',3,'Duet'),'stable after seeking');
assert.equal(lyricReaction('Unrelated unfamiliar sentence',3),null);
assert.equal(lyricReaction('I am sad and lonely',4).gif,null,'no GIF outside sparse eligible slots');
assert.ok(['🥺','😢',null].includes(lyricReaction('I am crying',2).emoji));
assert.ok(['❤️','🥰','🫶',null].includes(lyricReaction('dil mein pyar',2).emoji));
let count=0;
const ac=new AbortController();
assert.equal(await reactionGif('arbitrary lyric text',ac.signal,()=>{count++;}),null);
assert.equal(count,0,'unknown categories never generate requests');
assert.equal(await reactionGif('cry',ac.signal,async()=>({ok:true,json:async()=>({results:[{url:'https://evil.test/tracker.gif'}]})})),null);
let requested='';
const result=await reactionGif('hug',ac.signal,async url=>{requested=url;return {ok:true,json:async()=>({results:[{url:'https://nekos.best/api/v2/hug/test.gif'}]})};});
assert.equal(result.provider,'nekos.best');
assert.equal(requested,'https://nekos.best/api/v2/hug','no lyric/title/artist sent');
const dom=new JSDOM('<div><p><span class="w">love</span></p></div>');
globalThis.document=dom.window.document;
globalThis.matchMedia=()=>({matches:true});
const bubble=document.querySelector('div');
const viz={ctx:{song:{title:'Test'},opts:{emojis:()=>true,gifs:()=>true}}};
let i=0;while(!lyricReaction('love',i,'Test')?.emoji)i++;
addChatReaction(viz,bubble,'love',i);
assert.equal(bubble.querySelector('.w').textContent,'love','lyric words untouched');
assert.ok(bubble.querySelector('.chat-emoji'));
assert.equal(bubble.querySelector('.chat-gif'),null,'reduced motion prevents GIF attachment');
const off=document.createElement('div');off.innerHTML='<p>love</p>';
addChatReaction({ctx:{song:{title:'Test'},opts:{emojis:()=>false,gifs:()=>false}}},off,'love',i);
assert.equal(off.textContent,'love','off switches preserve undecorated lyrics');
console.log('Context reactions, sparse GIF slots, privacy, host validation, reduced motion and controls verified.');
