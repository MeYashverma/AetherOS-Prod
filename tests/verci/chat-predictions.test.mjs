import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {createPredictor,applyPrediction,predictionBar} from '../../src/vendor/verci/viz/chat-predictions.js';
const predict=createPredictor(['You are beautiful','You are beautiful','I miss moonlight']);
assert.ok(predict('bea').includes('beautiful'));
assert.equal(predict('you are ')[0],'beautiful');
assert.ok(predict('i mi').includes('miss'));
assert.deepEqual(predict('zzzzzz'),[]);
assert.deepEqual(predict('you are '),predict('you are '));
assert.equal(applyPrediction('I mi','miss').text,'I miss ');
assert.equal(applyPrediction('I ','love').text,'I love ');
assert.equal(applyPrediction('I mi you','miss',4,4).text,'I miss you');
const dom=new JSDOM('<textarea maxlength="280"></textarea>');globalThis.document=dom.window.document;
const input=document.querySelector('textarea');input.value='bea';input.setSelectionRange(3,3);
const bar=predictionBar(predict,input);document.body.append(bar);
assert.equal(bar.querySelector('button').textContent,'beautiful');bar.querySelector('button').click();
assert.equal(input.value,'beautiful ');assert.equal(document.activeElement,input);
input.value='i mi';input.setSelectionRange(4,4);input.dispatchEvent(new dom.window.Event('input'));
assert.ok([...bar.querySelectorAll('button')].some(b=>b.textContent==='miss'));
